async page => {
  const origin = 'http://127.0.0.1:5202', provider = 'http://127.0.0.1:55502';
  const checks = [];
  const check = (condition, message) => { if (!condition) throw new Error(message); checks.push(message); };
  const stats = async () => (await page.request.get(provider + '/__stats')).json();
  const heading = name => page.getByRole('heading', { name, exact: true });
  const click = name => page.getByRole('button', { name, exact: true }).click();
  const fill = (label, value) => page.getByLabel(label, { exact: true }).fill(value);
  const back = () => page.evaluate(() => !window.dispatchEvent(new Event('zolnutrition:back', { cancelable: true })));
  await page.context().route('https://*.supabase.co/**', route => route.abort());
  await page.request.post(provider + '/__reset');
  await page.clock.install();
  await page.goto(origin);
  await heading('Welcome back').waitFor();
  await click('Forgot password?');
  await heading('Reset your password').waitFor();
  await fill('Email', 'athlete@example.test');
  await click('Send recovery code');
  await heading('Enter recovery code').waitFor();
  check(await page.getByRole('alert').textContent().then(s => /If an account exists/.test(s)), 'Request uses a generic account-safe message');
  check(await page.getByRole('button', { name: /^Resend recovery code/ }).isDisabled(), 'Resend starts with a cooldown');
  await fill('Recovery code', '000000');
  await click('Verify recovery code');
  await page.getByRole('alert').filter({ hasText: /expired or is invalid/ }).waitFor();
  check((await stats()).updates === 0, 'Wrong OTP cannot update a password');
  await fill('Email', 'edited@example.test');
  await heading('Reset your password').waitFor();
  check(await page.getByLabel('Recovery code', { exact: true }).count() === 0, 'Editing email removes the old code stage');
  await fill('Email', 'athlete@example.test');
  await page.clock.runFor(61000);
  await click('Send recovery code');
  await heading('Enter recovery code').waitFor();
  await page.clock.runFor(61000);
  await click('Resend recovery code');
  check((await stats()).requests === 3, 'Resend uses another recovery request after cooldown');
  await fill('Recovery code', '123456');
  await click('Verify recovery code');
  await heading('Choose a new password').waitFor();
  check((await stats()).nutritionQueries === 0, 'A verified recovery session does not query nutrition data');
  check(await page.getByRole('button', { name: 'Sign out', exact: true }).count() === 0, 'Recovery does not become the ordinary signed-in header');
  await fill('New password', 'StrongPass123'); await fill('Confirm new password', 'Mismatch123');
  await click('Save new password');
  await page.getByRole('alert').filter({ hasText: /Passwords do not match/ }).waitFor();
  check((await stats()).updates === 0, 'Confirmation mismatch prevents password update');
  await fill('New password', 'short'); await fill('Confirm new password', 'short');
  await click('Save new password');
  check((await stats()).updates === 0 && await page.getByLabel('New password', { exact: true }).evaluate(el => !el.validity.valid), 'A password shorter than eight characters is rejected');
  await fill('New password', 'StrongPass123'); await fill('Confirm new password', 'StrongPass123');
  await click('Save new password');
  await heading('Welcome back').waitFor();
  check((await stats()).updates === 1 && (await stats()).logouts === 1, 'Valid recovery saves once and signs out');
  check(await page.getByLabel('Password', { exact: true }).inputValue() === '', 'New password is cleared when returning to sign in');
  check(await page.evaluate(() => [...Object.keys(localStorage), ...Object.keys(sessionStorage)].every(k => !/zolnutrition-recovery/.test(k))), 'Recovery auth tokens are never persisted');

  // A normal sign-in from another tab must not let App mount nutrition screens mid-reset.
  await click('Forgot password?'); await fill('Email', 'athlete@example.test');
  await page.clock.runFor(61000); await click('Send recovery code');
  await heading('Enter recovery code').waitFor(); await fill('Recovery code', '123456');
  await click('Verify recovery code'); await heading('Choose a new password').waitFor();
  await page.evaluate(async () => { const { sb } = await import('/src/client.js'); await sb.auth.signInWithPassword({ email: 'other@example.test', password: 'Synthetic123' }); });
  await heading('Reset your password').waitFor();
  check((await stats()).nutritionQueries === 0, 'App blocks nutrition queries during a normal-account switch in recovery');
  check(await page.getByLabel('New password', { exact: true }).count() === 0, 'Normal account switching invalidates verified proof');
  await page.evaluate(async () => { const { sb } = await import('/src/client.js'); await sb.auth.signOut({ scope: 'local' }); });
  await click('Back to sign in'); await heading('Welcome back').waitFor();

  await page.setViewportSize({ width: 390, height: 844 });
  await click('Forgot password?'); await fill('Email', 'athlete@example.test');
  await page.clock.runFor(61000); await click('Send recovery code');
  await heading('Enter recovery code').waitFor();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Recovery fits the mobile viewport');
  check(await back(), 'Android back is consumed at the recovery-code stage');
  await heading('Reset your password').waitFor();
  check(await back(), 'Android back returns from recovery to normal sign-in');
  await heading('Welcome back').waitFor();
  check(!await back(), 'Android back at sign-in retains normal minimize behavior');
  await click('Create an account'); await heading('Create account').waitFor();
  check(await page.getByLabel('Username', { exact: true }).count() === 1, 'Registration stays available');
  await click('Back to sign in');

  await page.request.post(provider + '/__settings', { data: { delay: 500 } });
  await click('Forgot password?'); await fill('Email', 'athlete@example.test');
  const beforeBusy = (await stats()).requests;
  await page.clock.runFor(61000); await click('Send recovery code');
  await page.getByRole('button', { name: 'Please wait…', exact: true }).waitFor();
  check(await page.getByLabel('Email', { exact: true }).isDisabled() && await page.getByRole('button', { name: 'Back to sign in', exact: true }).isDisabled(), 'Busy requests disable email editing and navigation');
  check(await back(), 'Android back is locked during an in-flight request');
  await page.locator('form').dispatchEvent('submit');
  await heading('Enter recovery code').waitFor();
  check((await stats()).requests === beforeBusy + 1, 'The request lock rejects a duplicate form submission');
  await page.request.post(provider + '/__settings', { data: { delay: 0 } });
  await fill('Recovery code', '123456'); await click('Verify recovery code');
  await heading('Choose a new password').waitFor();
  const beforeReload = (await stats()).nutritionQueries;
  await page.reload(); await heading('Welcome back').waitFor();
  check((await stats()).nutritionQueries === beforeReload, 'Refresh loses recovery proof without opening nutrition screens');
  check(await page.getByLabel('New password', { exact: true }).count() === 0, 'Refresh requires a fresh recovery code');
  await page.request.post(provider + '/__settings', { data: { rateLimit: true } });
  await click('Forgot password?'); await fill('Email', 'athlete@example.test'); await click('Send recovery code');
  await page.getByRole('alert').filter({ hasText: /countdown/ }).waitFor();
  check(await page.getByRole('button', { name: /^Send recovery code/ }).isDisabled(), 'Provider rate limits start the resend countdown');
  await page.request.post(provider + '/__settings', { data: { rateLimit: false } });
  await click('Back to sign in'); await heading('Welcome back').waitFor();

  await click('Forgot password?'); await fill('Email', 'athlete@example.test');
  await page.clock.runFor(61000); await click('Send recovery code');
  await heading('Enter recovery code').waitFor(); await fill('Recovery code', '123456');
  await click('Verify recovery code'); await heading('Choose a new password').waitFor();
  await page.request.post(provider + '/__settings', { data: { logoutFailure: true } });
  await fill('New password', 'StrongPass123'); await fill('Confirm new password', 'StrongPass123');
  const beforeCleanup = (await stats()).updates;
  await click('Save new password');
  await page.getByRole('alert').filter({ hasText: /Password saved/ }).waitFor();
  check(await page.getByLabel('New password', { exact: true }).count() === 0, 'An interrupted signout clears the saved password fields');
  await page.request.post(provider + '/__settings', { data: { logoutFailure: false } });
  await click('Return to sign in'); await heading('Welcome back').waitFor();
  check((await stats()).updates === beforeCleanup + 1, 'Retrying interrupted signout does not save the password again');
  await fill('Email', 'athlete@example.test'); await fill('Password', 'StrongPass123');
  await click('Sign In'); await heading('Set your daily targets').waitFor();
  check((await stats()).nutritionQueries === 1, 'Normal sign-in after reset resumes the existing onboarding flow');
  await click('Sign out'); await heading('Welcome back').waitFor();
  return { passed: checks.length, checks, stats: await stats() };
}
